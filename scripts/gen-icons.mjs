// Generates src/ui/common/icons.tsx from the UI kit's icons/*.svg (24×24, stroke 1.8, currentColor): inline SVG, no
// files at runtime (0.3.7: gear redrawn, see OVERRIDE). Usage: node scripts/gen-icons.mjs <ui-kit-dir>
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const dir = process.argv[2]?.replace(/\/$/, '') + '/icons';
// 0.3.7: the kit's gear is lopsided (uneven teeth, hub at (12,11), not the centre) and reads crooked at 16–18 px;
// redrawn here: 6 symmetric teeth, hub at (12,12), same stroke 1.8 / round joins. Reported to the kit.
const OVERRIDE = {
  'gear.svg': '<path d="M9.49 5.46 10.02 2.71 13.98 2.71 14.51 5.46 16.41 6.56 19.06 5.64 21.04 9.06 18.91 10.90 18.91 13.10 21.04 14.94 19.06 18.36 16.41 17.44 14.51 18.54 13.98 21.29 10.02 21.29 9.49 18.54 7.59 17.44 4.94 18.36 2.96 14.94 5.09 13.10 5.09 10.90 2.96 9.06 4.94 5.64 7.59 6.56z" /><circle cx="12" cy="12" r="2.8" />',
};
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const rows = readdirSync(dir).filter((f) => f.endsWith('.svg')).sort().map((f) => {
  const svg = readFileSync(`${dir}/${f}`, 'utf8').trim();
  const open = svg.match(/^<svg([^>]*)>/)[1];
  if (!/stroke="currentColor"/.test(open) || /<(style|script|image|foreignObject)|href=/i.test(svg)) throw new Error(`unexpected icon ${f}`);
  const inner = OVERRIDE[f] ?? svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '').replace(/\/>/g, ' />');
  if (/[a-z]+-[a-z]+=/.test(inner)) throw new Error(`dashed attribute in ${f}: convert to JSX`);
  return `  ${JSON.stringify(camel(f.replace(/\.svg$/, ''))).replace(/"/g, '').replace(/^(\w+)$/, '$1')}: (p: P) => <S {...p}>${inner}</S>,`;
});
writeFileSync('src/ui/common/icons.tsx', `// Interface icons of the UI kit 1.1.1 (icons/*.svg, generated by scripts/gen-icons.mjs — do not edit by hand):
// 24×24 grid, stroke 1.8, round caps and joins, currentColor; inline, decorative (aria-hidden), the meaning is in words.
import type { ReactNode } from 'react';

type P = { size?: number; className?: string };
const S = ({ children, size = 18, className }: P & { children: ReactNode }) => (
  <svg className={className ? \`ico \${className}\` : 'ico'} width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={1.8} strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" focusable="false">{children}</svg>
);

export const I = {
${rows.join('\n')}
  /** 0.3.7: drawn pointing down and centred on (12,12) — the kit's chevron points right and, rotated, sat 0.5 off */
  chevronDown: (p: P) => <S {...p}><path d="m6 9 6 6 6-6" /></S>,
};
`);
console.log(`icons.tsx: ${rows.length} icons`);
